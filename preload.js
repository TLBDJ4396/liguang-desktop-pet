const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('petAPI', {
  getBounds: () => ipcRenderer.invoke('win:get-bounds'),
  getPsdRatio: () => ipcRenderer.invoke('win:get-psd-ratio'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  readPsd: () => ipcRenderer.invoke('psd:read'),
  setBounds: (b) => ipcRenderer.send('win:set-bounds', b),
  setIgnoreMouse: (ignore) => ipcRenderer.send('win:set-ignore-mouse', ignore),
  showMenu: () => ipcRenderer.send('pet:menu'),
  notifyReady: () => ipcRenderer.send('page:ready'),
  updateConfig: (patch) => ipcRenderer.send('config:update', patch),
  onConfigChanged: (cb) => ipcRenderer.on('config:changed', (e, c) => cb(c)),
  onPsdReload: (cb) => ipcRenderer.on('psd:reload', () => cb()),
  onActionPlay: (cb) => ipcRenderer.on('action:play', (e, id) => cb(id)),
  onBubbleCustomSize: (cb) => ipcRenderer.on('bubble:customSize', () => cb()),
  onBubbleAdjust: (cb) => ipcRenderer.on('bubble:adjust', () => cb()),
  endBubbleAdjust: () => ipcRenderer.send('bubble:adjust-end'),
  onAiEnter: (cb) => ipcRenderer.on('ai:enter', (e, scene) => cb(scene)),
  onAiLong:  (cb) => ipcRenderer.on('ai:long',  (e, scene) => cb(scene)),
  onAiLeave: (cb) => ipcRenderer.on('ai:leave', (e, scene) => cb(scene)),
  onSysTrigger: (cb) => ipcRenderer.on('sys:trigger', (e, scene) => cb(scene)),
  onAppEnter: (cb) => ipcRenderer.on('app:enter', (e, scene) => cb(scene)),
  onHolidayTrigger: (cb) => ipcRenderer.on('holiday:trigger', (e, scene) => cb(scene)),
  onBirthdayEdit: (cb) => ipcRenderer.on('birthday:edit', () => cb()),
  onHolidaySync: (cb) => ipcRenderer.on('holiday:sync', () => cb()),
  onLogView: (cb) => ipcRenderer.on('log:view', () => cb()),
  onLogCleared: (cb) => ipcRenderer.on('log:cleared', () => cb()),
  appendLog: (entry) => ipcRenderer.send('log:append', entry),
  readLog: () => ipcRenderer.invoke('log:read'),
  getTodayInfo: () => ipcRenderer.invoke('holiday:today'),
  recordStat: (scene) => ipcRenderer.send('stats:record', scene),
  getAllStats: () => ipcRenderer.invoke('stats:get-all'),
  clearStats: () => ipcRenderer.send('stats:clear'),
  pomodoroStart: () => ipcRenderer.send('pomodoro:start-ipc'),
  pomodoroPause: () => ipcRenderer.send('pomodoro:pause-ipc'),
  pomodoroResume: () => ipcRenderer.send('pomodoro:resume-ipc'),
  pomodoroStop: () => ipcRenderer.send('pomodoro:stop-ipc'),
  pomodoroSetConfig: (w, b) => ipcRenderer.send('pomodoro:set-config-ipc', w, b),
  pomodoroGetState: () => ipcRenderer.invoke('pomodoro:get-state-ipc'),
  onPomodoroWorkEnd: (cb) => ipcRenderer.on('pomodoro:work_end', () => cb()),
  onPomodoroBreakEnd: (cb) => ipcRenderer.on('pomodoro:break_end', () => cb()),
  onPomodoroStart: (cb) => ipcRenderer.on('pomodoro:start', () => cb()),
  onPomodoroStop: (cb) => ipcRenderer.on('pomodoro:stop', () => cb()),
  onPomodoroTick: (cb) => ipcRenderer.on('pomodoro:tick', (e, d) => cb(d)),
  onPomodoroOpenSettings: (cb) => ipcRenderer.on('pomodoro:open-settings', () => cb()),
  onCoreMorningTea: (cb) => ipcRenderer.on('core:morning_tea', () => cb()),
  reportLog: (entry) => ipcRenderer.send('log:report', entry),
  onOpenLog: (cb) => ipcRenderer.on('log:open', () => cb()),
  sendBubble: (text) => ipcRenderer.send('bubble:show', text),
  hideBubble: () => ipcRenderer.send('bubble:hide')
});
